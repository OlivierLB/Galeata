#!/bin/sh
# Galeata installer for Linux x86_64 — no sudo, no system dependency.
#
#   curl -fsSL https://raw.githubusercontent.com/OlivierLB/Galeata/main/install.sh | sh
#
# Downloads the AppImage of the latest GitHub Release (all libraries bundled),
# verifies its SHA-256, extracts it under ~/.local/share/galeata (no FUSE needed,
# faster start than mounting the AppImage), and adds Galeata to the application
# menu and to ~/.local/bin. Running it again updates Galeata. Projects, plans and
# preferences (~/.local/share/dev.olivierlb.galeata) are never touched.
#
# Options:   --uninstall   remove Galeata (keeps your data)
# Variables: GALEATA_VERSION=v0.2.0      install a given release instead of the latest
#            GALEATA_DOWNLOAD_URL=URL    directory holding the release assets
#            GALEATA_BIN_DIR=DIR         launcher directory (default ~/.local/bin)
#
# Everything runs inside main(), called on the last line: a truncated download
# never executes a partial script.

set -eu

REPOSITORY="OlivierLB/Galeata"
ASSET="galeata-linux-x86_64.AppImage"
MARKER="# Generated by the Galeata installer"
KEEP_VERSIONS=2

say() { printf '%s\n' "$*"; }
fail() {
    printf 'Installation interrompue : %s\n' "$*" >&2
    exit 1
}

# Download $1 to $2 with curl or wget. Only HTTPS, except for an explicit
# GALEATA_DOWNLOAD_URL (used by tests and mirrors), which may also be file://.
fetch() {
    if command -v curl >/dev/null 2>&1; then
        protocols='=https'
        [ -n "${GALEATA_DOWNLOAD_URL:-}" ] && protocols='=https,file'
        curl -fsSL --proto "$protocols" --retry 3 -o "$2" "$1" || return 1
    elif command -v wget >/dev/null 2>&1; then
        wget -q -O "$2" "$1" || return 1
    else
        fail "curl ou wget est nécessaire pour télécharger Galeata."
    fi
}

# Refuse to overwrite a file the installer did not create.
ensure_ours() {
    if [ -L "$1" ] || { [ -e "$1" ] && ! grep -qF "$MARKER" "$1" 2>/dev/null; }; then
        fail "fichier existant conservé : $1. Déplacez-le puis relancez l’installation."
    fi
}

# Atomically writes stdin to $1 with mode $2.
write_file() {
    mkdir -p "$(dirname "$1")"
    tmp_file=$(mktemp "$(dirname "$1")/.galeata-XXXXXX")
    cat >"$tmp_file"
    chmod "$2" "$tmp_file"
    mv -f "$tmp_file" "$1"
}

# Quotes a value for a .desktop Exec/Icon key.
desktop_quote() {
    printf '"%s"' "$(printf '%s' "$1" | sed -e 's/%/%%/g' -e 's/[\\"`$]/\\&/g')"
}

# Single-quotes a value for a POSIX shell script.
shell_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

paths() {
    data_dir="${XDG_DATA_HOME:-$HOME/.local/share}"
    prefix="$data_dir/galeata"
    bin_dir="${GALEATA_BIN_DIR:-$HOME/.local/bin}"
    launcher="$bin_dir/galeata"
    desktop="$data_dir/applications/dev.olivierlb.galeata.desktop"
}

uninstall() {
    paths
    for file in "$launcher" "$desktop"; do
        if [ -e "$file" ] || [ -L "$file" ]; then
            ensure_ours "$file"
            rm -f "$file"
        fi
    done
    rm -rf "$prefix"
    command -v update-desktop-database >/dev/null 2>&1 &&
        update-desktop-database "$data_dir/applications" >/dev/null 2>&1 || true
    say "Galeata est désinstallée. Vos projets, plans et préférences sont conservés"
    say "dans $data_dir/dev.olivierlb.galeata."
}

# The executable and its helpers may load bundled libraries long after startup.
# Keep their whole version directory until every process using it has exited.
version_in_use() {
    printf '%s\n' "$running_executables" | {
        while IFS= read -r executable; do
            case "$executable" in
            "$1"/*) exit 0 ;;
            esac
        done
        exit 1
    }
}

# Keeps the current version, the most recent other ones and any active versions.
prune_versions() {
    # Without procfs, do not risk removing files from a running application.
    [ -d /proc/self ] || return 0
    running_executables=$(readlink /proc/[0-9]*/exe 2>/dev/null || true)
    current_target=$(readlink "$prefix/current" 2>/dev/null || true)
    # Newest first. Version names are hex digests; the prefix may contain spaces.
    ls -1dt "$prefix/versions"/*/ 2>/dev/null | {
        kept=0
        while IFS= read -r dir; do
            dir=${dir%/}
            [ "$dir" = "$current_target" ] && continue
            kept=$((kept + 1))
            if [ "$kept" -ge "$KEEP_VERSIONS" ]; then
                version_in_use "$dir" && continue
                rm -rf "$dir"
            fi
        done
    }
}

report_agents() {
    found=""
    if command -v claude >/dev/null 2>&1; then
        say "  Claude Code : détecté"
        found=1
    else
        say "  Claude Code : absent"
    fi
    if command -v codex >/dev/null 2>&1; then
        say "  Codex       : détecté"
        found=1
    else
        say "  Codex       : absent"
    fi
    if [ -z "$found" ]; then
        say "Galeata a besoin de Claude Code ou de Codex (un seul suffit)."
        say "Il vous guidera pour l’installer au premier lancement."
    fi
}

install() {
    [ "$(uname -s)" = "Linux" ] || fail "Galeata est disponible pour Linux uniquement."
    case "$(uname -m)" in
    x86_64 | amd64) ;;
    *) fail "architecture $(uname -m) non prise en charge (x86_64 uniquement)." ;;
    esac
    command -v sha256sum >/dev/null 2>&1 || fail "sha256sum est nécessaire (paquet coreutils)."
    paths
    ensure_ours "$launcher"
    ensure_ours "$desktop"
    if [ -e "$prefix/current" ] && [ ! -L "$prefix/current" ]; then
        fail "$prefix/current existe et n’est pas un lien créé par l’installateur."
    fi

    if [ -n "${GALEATA_DOWNLOAD_URL:-}" ]; then
        base="${GALEATA_DOWNLOAD_URL%/}"
    elif [ -n "${GALEATA_VERSION:-}" ]; then
        base="https://github.com/$REPOSITORY/releases/download/$GALEATA_VERSION"
    else
        base="https://github.com/$REPOSITORY/releases/latest/download"
    fi

    work=$(mktemp -d "${TMPDIR:-/tmp}/galeata-install-XXXXXX")
    trap 'rm -rf "$work"' EXIT
    trap 'exit 130' INT TERM

    version=""
    if fetch "$base/VERSION" "$work/VERSION" 2>/dev/null; then
        version=$(head -c 64 "$work/VERSION" | tr -cd 'A-Za-z0-9._+-')
    fi
    say "Téléchargement de Galeata${version:+ $version}…"
    fetch "$base/SHA256SUMS" "$work/SHA256SUMS" ||
        fail "impossible de télécharger $base/SHA256SUMS. Vérifiez votre connexion."
    fetch "$base/$ASSET" "$work/$ASSET" ||
        fail "impossible de télécharger $base/$ASSET. Vérifiez votre connexion."
    expected=$(awk -v asset="$ASSET" '$2 == asset || $2 == "*" asset { print $1; exit }' "$work/SHA256SUMS")
    [ -n "$expected" ] || fail "empreinte de $ASSET absente de SHA256SUMS."
    actual=$(sha256sum "$work/$ASSET" | cut -d ' ' -f 1)
    [ "$expected" = "$actual" ] ||
        fail "empreinte SHA-256 incorrecte (attendue $expected, obtenue $actual). Fichier rejeté."
    say "Empreinte SHA-256 vérifiée."

    # Extracting avoids requiring FUSE (absent by default on recent Ubuntu)
    # and the cost of mounting the image at every start.
    chmod +x "$work/$ASSET"
    (cd "$work" && "./$ASSET" --appimage-extract >/dev/null 2>&1) ||
        fail "extraction de l’AppImage impossible."
    [ -x "$work/squashfs-root/AppRun" ] || fail "AppImage invalide : AppRun absent."

    release="$prefix/versions/$(printf '%s' "$actual" | cut -c 1-16)"
    mkdir -p "$prefix/versions"
    if [ ! -d "$release" ]; then
        staging=$(mktemp -d "$prefix/versions/.install-XXXXXX")
        cp -a "$work/squashfs-root/." "$staging/"
        mv "$staging" "$release"
    fi
    ln -sfn "$release" "$prefix/.current-new"
    mv -Tf "$prefix/.current-new" "$prefix/current"
    touch "$release"

    icon=""
    for candidate in "$release"/*.png "$release/.DirIcon"; do
        if [ -f "$candidate" ]; then
            icon="$prefix/current/${candidate##*/}"
            break
        fi
    done

    # Applications started from the menu do not inherit the terminal PATH
    # (nvm, ~/.local/bin…): remember where the agent CLIs are today.
    extra_path=""
    for command in claude codex node rg git; do
        found=$(command -v "$command" 2>/dev/null || true)
        case "$found" in
        /*)
            dir=$(dirname "$found")
            case ":$extra_path:" in
            *":$dir:"*) ;;
            *) extra_path="${extra_path:+$extra_path:}$dir" ;;
            esac
            ;;
        esac
    done

    write_file "$launcher" 755 <<EOF
#!/bin/sh
$MARKER
export PATH=$(shell_quote "$extra_path")":\${PATH:-/usr/bin:/bin}"
exec $(shell_quote "$prefix/current/AppRun") "\$@"
EOF
    write_file "$desktop" 644 <<EOF
$MARKER
[Desktop Entry]
Type=Application
Name=Galeata
Comment=Développer avec vos agents
Exec=$(desktop_quote "$launcher")
${icon:+Icon=$icon}
Terminal=false
Categories=Development;IDE;
StartupNotify=true
StartupWMClass=galeata
EOF
    command -v update-desktop-database >/dev/null 2>&1 &&
        update-desktop-database "$data_dir/applications" >/dev/null 2>&1 || true
    prune_versions

    say "Galeata${version:+ $version} est installée dans le menu des applications."
    say "Commande : $launcher"
    case ":$PATH:" in
    *":$bin_dir:"*) ;;
    *) say "Ajoutez $bin_dir à votre PATH pour lancer « galeata » depuis un terminal." ;;
    esac
    report_agents
}

main() {
    case "${1:-}" in
    --uninstall) uninstall ;;
    -h | --help) sed -n '2,19p' "$0" 2>/dev/null || say "Voir https://github.com/$REPOSITORY" ;;
    "") install ;;
    *) fail "option inconnue : $1 (options : --uninstall, --help)" ;;
    esac
}

main "$@"
