#!/usr/bin/env python3
"""Install a validated Linux build for the current user, without sudo or Rust."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess
import sys
import tempfile
import zipfile

REPOSITORY = "OlivierLB/Galeata"
MARKER = "# Generated by the Galeata installer"


def run(argv, **kwargs):
    result = subprocess.run(argv, text=True, capture_output=True, **kwargs)
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or f"Commande échouée : {argv[0]}")
    return result.stdout.strip()


def desktop_quote(value):
    value = str(value).replace("%", "%%")
    for character in ("\\", '"', "`", "$"):
        value = value.replace(character, "\\" + character)
    return '"' + value + '"'


def atomic_text(path, content, mode):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix=".galeata-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w") as stream:
            stream.write(content)
        os.chmod(name, mode)
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


def install(args):
    if platform.system() != "Linux" or platform.machine() not in ("x86_64", "amd64"):
        raise RuntimeError("Ce paquet est destiné à Linux x86_64.")
    for command in ("dpkg-deb", "ldd"):
        if not shutil.which(command):
            raise RuntimeError(f"Outil système manquant : {command}")
    args.data_dir = args.data_dir.expanduser().absolute()
    args.bin_dir = args.bin_dir.expanduser().absolute()
    prefix = args.data_dir / "galeata"
    desktop = args.data_dir / "applications" / "dev.olivierlb.galeata.desktop"
    launcher = args.bin_dir / "galeata"
    current = prefix / "current"
    for path in (desktop, launcher):
        if path.exists() or path.is_symlink():
            if path.is_symlink() or MARKER not in path.read_text(errors="replace"):
                raise RuntimeError(f"Fichier existant conservé : {path}. Déplacez-le avant l’installation.")
    if current.exists() and not current.is_symlink():
        raise RuntimeError(f"Le chemin {current} existe et n’est pas un lien d’installation.")

    with tempfile.TemporaryDirectory(prefix="galeata-install-") as temporary:
        temporary = Path(temporary)
        if args.archive:
            archive = args.archive.expanduser().resolve(strict=True)
        else:
            if not shutil.which("gh"):
                raise RuntimeError("GitHub CLI est requis pour télécharger le paquet. Autre possibilité : --archive chemin/vers/galeata-linux-deb.zip.")
            run_id = args.run_id
            if not run_id:
                builds = json.loads(run(["gh", "run", "list", "--repo", REPOSITORY, "--workflow", "ci.yml", "--branch", "main", "--status", "success", "--limit", "1", "--json", "databaseId"]))
                if not builds:
                    raise RuntimeError("Aucune compilation réussie trouvée.")
                run_id = str(builds[0]["databaseId"])
            print(f"Téléchargement de Galeata depuis la compilation {run_id}…", flush=True)
            try:
                run(["gh", "run", "download", str(run_id), "--repo", REPOSITORY, "--name", "galeata-linux-deb", "--dir", str(temporary / "download")])
            except RuntimeError as error:
                raise RuntimeError(f"Téléchargement impossible. Vérifiez le réseau et la connexion GitHub avec gh auth login.\n{error}") from error
            packages = list((temporary / "download").rglob("*.deb"))
            if len(packages) != 1:
                raise RuntimeError("Le téléchargement ne contient pas un unique paquet Debian.")
            archive = packages[0]

        if archive.suffix == ".zip":
            with zipfile.ZipFile(archive) as package_zip:
                packages = [item for item in package_zip.infolist() if item.filename.endswith(".deb") and not item.is_dir()]
                if len(packages) != 1 or packages[0].file_size > 150_000_000:
                    raise RuntimeError("Archive de distribution invalide.")
                package = temporary / "galeata.deb"
                package.write_bytes(package_zip.read(packages[0]))
        else:
            package = archive
        if run(["dpkg-deb", "--field", str(package), "Package"]).lower() != "galeata":
            raise RuntimeError("Ce paquet n’est pas Galeata.")
        if run(["dpkg-deb", "--field", str(package), "Architecture"]) != "amd64":
            raise RuntimeError("Architecture de paquet incompatible.")
        extracted = temporary / "extracted"
        run(["dpkg-deb", "--extract", str(package), str(extracted)])
        binary = extracted / "usr/bin/galeata"
        bridges = list((extracted / "usr/lib").rglob("galeata-mcp"))
        if not binary.is_file() or len(bridges) != 1 or not bridges[0].is_file():
            raise RuntimeError("Exécutable ou passerelle MCP absent du paquet.")
        for executable in (binary, bridges[0]):
            result = subprocess.run(["ldd", str(executable)], text=True, capture_output=True, env={**os.environ, "LC_ALL": "C"})
            output = result.stdout + result.stderr
            if "not found" in output or (result.returncode and "not a dynamic executable" not in output and "statically linked" not in output):
                raise RuntimeError(f"Dépendances système incompatibles pour {executable.name} :\n{output}")
        # Tauri can locate the bridge beside its executable in this user-local layout.
        shutil.copy2(bridges[0], binary.with_name("galeata-mcp"))
        icons = list((extracted / "usr/share/icons").rglob("*.png"))
        if not icons:
            raise RuntimeError("Icône de l’application absente.")
        icon_relative = max(icons, key=lambda path: path.stat().st_size).relative_to(extracted)
        digest = hashlib.sha256(package.read_bytes()).hexdigest()[:16]
        release = prefix / "versions" / digest
        release.parent.mkdir(parents=True, exist_ok=True)
        if not release.exists():
            staging = Path(tempfile.mkdtemp(prefix=".install-", dir=release.parent))
            try:
                shutil.copytree(extracted, staging, dirs_exist_ok=True)
                os.replace(staging, release)
            finally:
                if staging.exists():
                    shutil.rmtree(staging)
        next_link = prefix / ".current-new"
        next_link.unlink(missing_ok=True)
        next_link.symlink_to(release, target_is_directory=True)
        os.replace(next_link, current)
        paths = []
        for command in ("node", "npm", "codex", "claude", "rg", "git"):
            executable = shutil.which(command)
            if executable and str(Path(executable).parent) not in paths:
                paths.append(str(Path(executable).parent))
        path_prefix = shlex.quote(":".join(paths))
        atomic_text(launcher, f'#!/usr/bin/env bash\n{MARKER}\nexport PATH={path_prefix}:"${{PATH:-/usr/bin:/bin}}"\nexec {shlex.quote(str(current / "usr/bin/galeata"))} "$@"\n', 0o755)
        atomic_text(desktop, f'{MARKER}\n[Desktop Entry]\nType=Application\nName=Galeata\nComment=Développer avec vos agents\nExec={desktop_quote(launcher)}\nIcon={current / icon_relative}\nTerminal=false\nCategories=Development;IDE;\nStartupNotify=true\n', 0o644)
        if shutil.which("update-desktop-database"):
            subprocess.run(["update-desktop-database", str(desktop.parent)], capture_output=True)
        print(f"Galeata est installée dans le menu des applications.\nCommande : {launcher}\nInstallation : {release}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, help="Archive ZIP ou paquet Debian déjà téléchargé")
    parser.add_argument("--run-id", help="Compilation GitHub Actions à installer")
    parser.add_argument("--data-dir", type=Path, default=Path(os.environ.get("XDG_DATA_HOME", str(Path.home() / ".local/share"))))
    parser.add_argument("--bin-dir", type=Path, default=Path.home() / ".local/bin")
    args = parser.parse_args()
    try:
        install(args)
    except (OSError, RuntimeError, ValueError, zipfile.BadZipFile) as error:
        print(f"Installation interrompue : {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
